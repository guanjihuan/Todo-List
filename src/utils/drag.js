// 拖拽相关常量与共用工具
//
// 用途：消除 task-list.js（_setupDrag）与 sidebar.js（_setupSidebarDrag）之间
// 重复声明的拖拽阈值。两边阈值不一致会直接表现为「同一个指针移动 5px，一处
// 已经认为开始拖拽、另一处还在判定为点击」—— 用户体感是「拖到一半突然抖一下」。

/**
 * 拖拽激活阈值（像素）。
 *
 * 指针按下后移动距离超过该阈值才视作「开始拖拽」，否则视为点击。
 * 4px 是经验值 —— 小于这个值容易把抖动的手指误判为拖拽（特别是触摸板），
 * 大于这个值用户需要先「抖」一下才开始拖，体验拖沓。
 *
 * 改动此值需要同步 review 两边的拖拽交互；集中常量就是为了避免漏改。
 */
export const DRAG_THRESHOLD = 4;
